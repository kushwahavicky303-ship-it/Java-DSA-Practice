package Arrays;

public class Traversal {
    public static void main(String args[]){
        System.out.println("welcome to the array traversal:");
        int[] arr ={10, 20, 30, 40, 50};
        for(int i=0; i<arr.length; i++){
            System.out.println("array traversal: " +arr[i]);
        }
    }
}
